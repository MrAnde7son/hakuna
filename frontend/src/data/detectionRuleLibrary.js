/** Group templates by category for easy UI rendering. */
export function groupTemplatesByCategory(templates = DETECTION_RULE_TEMPLATES) {
  const map = {}
  for (const tpl of templates) {
    if (!map[tpl.category]) map[tpl.category] = []
    map[tpl.category].push(tpl)
  }
  return map
}

/**
 * Convert a library template to a RuleCreate payload. Strips UI-only fields
 * (id, category, attribution, references, note) so the backend only sees
 * DetectionRule columns.
 */
export function templateToRulePayload(template) {
  return {
    name: template.name,
    description: template.description,
    severity: template.severity,
    query: template.query || {},
    threshold: template.threshold ?? 1,
    window_seconds: template.window_seconds ?? 300,
    group_by: template.group_by || [],
    schedule_minutes: template.schedule_minutes ?? 5,
    mitre_techniques: template.mitre_techniques || [],
    enabled: true,
  }
}
