"""Tests for js_secret_scanner.

Critical safety property: no test fixture contains a real secret. Every
"secret" used here is either a documented test value (AWS example key,
Stripe test key) or a structurally valid but semantically invalid token
(e.g. a JWT signed with the empty string).
"""
import hashlib

from app.ingest.js_secret_scanner import (
    SecretHit,
    _redact,
    _shannon_entropy,
    scan_js_for_secrets,
)


# ── _redact ─────────────────────────────────────────────────────


class TestRedact:
    def test_long_secret_shows_first_and_last_4(self):
        assert _redact("AKIAIOSFODNN7EXAMPLE") == "AKIA…MPLE"

    def test_short_secret_returns_stars(self):
        """No first/last visibility for tokens ≤ 8 chars — half the secret
        in plaintext is too much."""
        assert _redact("abc") == "***"
        assert _redact("12345678") == "***"

    def test_value_equality_redacts_consistently(self):
        """Same input → same redacted output (matters for dedup display)."""
        v = "ghp_1234567890abcdefghij1234567890abcdef"
        assert _redact(v) == _redact(v)


# ── _shannon_entropy ────────────────────────────────────────────


class TestShannonEntropy:
    def test_uniform_string_high_entropy(self):
        # 64 unique characters in random order → entropy near log2(64) = 6
        s = "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789+/"
        assert _shannon_entropy(s) > 5.5

    def test_repetitive_string_low_entropy(self):
        assert _shannon_entropy("aaaaaaaaaaaaaaaaaaaaaaaa") < 0.5

    def test_empty_string_returns_zero(self):
        assert _shannon_entropy("") == 0.0


# ── scan_js_for_secrets ─────────────────────────────────────────


class TestScanJsForSecrets:
    def test_aws_example_key_detected(self):
        # AKIAIOSFODNN7EXAMPLE is the canonical AWS docs example.
        js = 'const config = { accessKey: "AKIAIOSFODNN7EXAMPLE" };'
        hits = scan_js_for_secrets(js, "https://example.com/app.js")
        assert any(h.secret_type == "aws_access_key" for h in hits)

    def test_invalid_aws_prefix_rejected(self):
        """Random ALL-CAPS string that starts with the wrong issuer prefix
        should fail the validator and not produce a hit."""
        js = 'const x = "ZZZZIOSFODNN7EXAMPLE"'
        hits = scan_js_for_secrets(js, "https://example.com/app.js")
        assert not any(h.secret_type == "aws_access_key" for h in hits)

    def test_jwt_with_valid_header_detected(self):
        # Header: {"alg":"HS256","typ":"JWT"}, payload: {"sub":"x"}, sig: empty
        # Generated by hand — base64url, no padding.
        jwt = "eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJzdWIiOiJ4In0.signature_placeholder"
        js = f'const token = "{jwt}";'
        hits = scan_js_for_secrets(js, "https://example.com/app.js")
        assert any(h.secret_type == "jwt" for h in hits)

    def test_jwt_with_undecodable_header_rejected(self):
        """Three dotted base64url-ish parts where the header doesn't decode
        to JSON-with-alg should not be flagged."""
        fake = "eyJhYWFhYWFhYWFhYWFhYWFhYWE.eyJYWFhYWFhYWFhYWFhYWFhYWE.AAAAAAAAAAAAAAAAAAAAAAA"
        js = f'const token = "{fake}";'
        hits = scan_js_for_secrets(js, "https://example.com/app.js")
        assert not any(h.secret_type == "jwt" for h in hits)

    def test_github_pat_detected(self):
        # Documented format ghp_<36 chars>; using filler chars that match the regex
        pat = "ghp_" + "A" * 36
        js = f'export const TOKEN = "{pat}";'
        hits = scan_js_for_secrets(js, "https://example.com/app.js")
        assert any(h.secret_type == "github_pat" for h in hits)

    def test_dedup_within_one_file(self):
        """Same secret repeated → one hit, not many."""
        secret = "AKIAIOSFODNN7EXAMPLE"
        js = f'const a = "{secret}"; const b = "{secret}"; const c = "{secret}";'
        hits = [h for h in scan_js_for_secrets(js, "x") if h.secret_type == "aws_access_key"]
        assert len(hits) == 1

    def test_redacted_form_in_hit_never_contains_full_secret(self):
        """Critical property: ``redacted`` must never carry the raw key."""
        secret = "AKIAIOSFODNN7EXAMPLE"
        js = f'const x = "{secret}";'
        hits = scan_js_for_secrets(js, "x")
        for h in hits:
            assert secret not in h.redacted

    def test_snippet_redacts_the_secret(self):
        """Snippet must show context but with the secret blanked."""
        secret = "AKIAIOSFODNN7EXAMPLE"
        js = f'const config = {{ accessKey: "{secret}" }};'
        hits = [h for h in scan_js_for_secrets(js, "x") if h.secret_type == "aws_access_key"]
        assert hits
        assert secret not in hits[0].snippet

    def test_sha256_consistent_across_files(self):
        """Same secret in two files → same SHA-256 (so backend dedup works)."""
        secret = "AKIAIOSFODNN7EXAMPLE"
        js1 = f'const a = "{secret}"'
        js2 = f'const b = "{secret}"'
        h1 = [h for h in scan_js_for_secrets(js1, "x") if h.secret_type == "aws_access_key"][0]
        h2 = [h for h in scan_js_for_secrets(js2, "y") if h.secret_type == "aws_access_key"][0]
        assert h1.sha256 == h2.sha256
        assert h1.sha256 == hashlib.sha256(secret.encode()).hexdigest()

    def test_high_entropy_pattern_skips_png_data(self):
        """Inline base64 PNG triggers the entropy regex but is denied."""
        png = "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAA" + "B" * 60
        js = f'const icon = "{png}";'
        hits = scan_js_for_secrets(js, "x")
        assert not any(h.secret_type == "high_entropy_string" for h in hits)

    def test_empty_content_returns_empty(self):
        assert scan_js_for_secrets("", "x") == []

    def test_line_hint_is_one_based(self):
        """Snippet metadata should point to a line operators can navigate to."""
        js = "// comment\n// another\nconst x = \"AKIAIOSFODNN7EXAMPLE\";\n"
        hits = [h for h in scan_js_for_secrets(js, "x") if h.secret_type == "aws_access_key"]
        assert hits[0].line_hint == 3

    def test_severity_present_on_each_hit(self):
        secret = "AKIAIOSFODNN7EXAMPLE"
        hits = scan_js_for_secrets(f'const x = "{secret}";', "x")
        for h in hits:
            assert h.severity in ("critical", "high", "medium", "low", "info")


# ── SecretHit dataclass ─────────────────────────────────────────


class TestSecretHit:
    def test_to_dict_round_trips(self):
        hit = SecretHit(
            secret_type="aws_access_key",
            severity="high",
            sha256="0" * 64,
            redacted="AKIA…MPLE",
            source_url="https://example.com/app.js",
            snippet="const x = AKIA…MPLE",
            line_hint=42,
        )
        d = hit.to_dict()
        assert d["secret_type"] == "aws_access_key"
        assert d["line_hint"] == 42
