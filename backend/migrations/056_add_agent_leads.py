"""Add `agent_leads` — durable storage for `emit_lead` tool output.

Phase 4 of the Cross-Scan Chain Coordinator (see
`docs/cross-scan-chain-coordinator-plan.md`). When a budget-bounded audit
agent observes something it didn't pursue (e.g. SMB audit ends with
"lsarpc reachable on three other DCs in this domain"), it calls
`emit_lead` to record the observation. The Coordinator's
`lead_followup` pattern consumes open leads on the next tick and
dispatches the suggested probe.

Distinct from `agent_runs.trace` which is run-scoped and ephemeral —
leads outlive the run and are queryable across ticks.
"""

