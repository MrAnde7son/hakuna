"""Add `coordinator_pending_approvals` — durable queue of approval-gated
chain-coordinator hypotheses awaiting an operator decision.

Phase 3/4 of the Cross-Scan Chain Coordinator (see
`docs/cross-scan-chain-coordinator-plan.md`). The `cred_found` pattern
(and any future approval-gated pattern) emits hypotheses with
`requires_approval=True`. Without persistence those hypotheses were
silently dropped at dispatch — the operator had no surface to see or
act on them. This table is that surface.

The Coordinator tick upserts one row per
`(org_id, asset_id, pattern, protocol, mission)` — re-enumeration just
bumps `last_seen_at`. Operator decisions flip `status` to
`approved` (triggers dispatch on the next tick via
`_dispatch_hypothesis` honoring the row) or `rejected`.
"""

