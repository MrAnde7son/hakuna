"""
Migration: Add SAML 2.0 SSO support.

- Creates saml_configs table for per-org SAML IdP configuration
- Adds saml_subject_id column to users table for SAML NameID linking

Safe to run multiple times (checks for table/column existence before adding).
Works with both SQLite and PostgreSQL.

Usage:
    cd backend
    python migrations/017_add_saml_sso.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sqlalchemy import text, inspect
from core.database import engine, DATABASE_URL


_is_pg = DATABASE_URL.startswith("postgresql")


def _table_exists(conn, table: str) -> bool:
    insp = inspect(conn)
    return table in insp.get_table_names()


def _column_exists(conn, table: str, column: str) -> bool:
    insp = inspect(conn)
    columns = [c["name"] for c in insp.get_columns(table)]
    return column in columns


def upgrade():
    with engine.connect() as conn:
        # 1. Create saml_configs table
        if not _table_exists(conn, "saml_configs"):
            conn.execute(text("""
                CREATE TABLE saml_configs (
                    id INTEGER PRIMARY KEY {autoincrement},
                    org_id INTEGER NOT NULL UNIQUE REFERENCES organizations(id),
                    is_enabled BOOLEAN DEFAULT FALSE,
                    idp_entity_id VARCHAR NOT NULL,
                    idp_sso_url VARCHAR NOT NULL,
                    idp_slo_url VARCHAR,
                    idp_x509_cert TEXT NOT NULL,
                    sp_entity_id VARCHAR,
                    default_role VARCHAR DEFAULT 'analyst',
                    auto_provision BOOLEAN DEFAULT TRUE,
                    force_sso BOOLEAN DEFAULT FALSE,
                    attribute_mapping JSON DEFAULT '{json_default}',
                    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """.format(
                autoincrement="GENERATED BY DEFAULT AS IDENTITY" if _is_pg else "AUTOINCREMENT",
                json_default="{}",
            )))
            conn.execute(text("CREATE INDEX ix_saml_config_org ON saml_configs (org_id)"))
            print("Created saml_configs table.")
        else:
            print("saml_configs table already exists, skipping.")

        # 2. Add saml_subject_id column to users
        if not _column_exists(conn, "users", "saml_subject_id"):
            conn.execute(text("ALTER TABLE users ADD COLUMN saml_subject_id VARCHAR"))
            conn.execute(text("CREATE INDEX ix_users_saml_subject_id ON users (saml_subject_id)"))
            print("Added saml_subject_id column to users table.")
        else:
            print("saml_subject_id column already exists, skipping.")

        conn.commit()
        print("Migration complete: SAML SSO tables added.")


def downgrade():
    with engine.connect() as conn:
        if _is_pg:
            conn.execute(text("DROP TABLE IF EXISTS saml_configs"))
            conn.execute(text("DROP INDEX IF EXISTS ix_users_saml_subject_id"))
            conn.execute(text("ALTER TABLE users DROP COLUMN IF EXISTS saml_subject_id"))
        else:
            conn.execute(text("DROP TABLE IF EXISTS saml_configs"))
            conn.execute(text("DROP INDEX IF EXISTS ix_users_saml_subject_id"))
            # SQLite does not support DROP COLUMN
        conn.commit()
        print("Downgraded: Dropped saml_configs table and saml_subject_id column.")


if __name__ == "__main__":
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--downgrade", action="store_true")
    args = parser.parse_args()

    if args.downgrade:
        downgrade()
    else:
        upgrade()
